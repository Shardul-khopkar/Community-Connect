create table if not exists public.connections (
    id bigint generated by default as identity primary key,
    request_id bigint not null references public.help_requests(id) on delete cascade,
    helper_id uuid not null references public.profiles(id) on delete cascade,
    score integer not null check (score between 0 and 100),
    score_components jsonb not null default '{}'::jsonb,
    status text not null default 'pending' check (status in ('pending', 'accepted', 'rejected')),
    seeker_accepted boolean not null default false,
    helper_accepted boolean not null default false,
    created_at timestamptz not null default now(),
    unique (request_id, helper_id)
);

alter table public.connections add column if not exists score_components jsonb not null default '{}'::jsonb;

create table if not exists public.helper_ratings (
    id bigint generated by default as identity primary key,
    helper_id uuid not null references public.profiles(id) on delete cascade,
    rater_id uuid not null references public.profiles(id) on delete cascade,
    connection_id bigint not null references public.connections(id) on delete cascade,
    rating smallint not null check (rating between 1 and 5),
    created_at timestamptz not null default now(),
    unique (connection_id, rater_id)
);

create table if not exists public.match_results (
    request_id bigint not null references public.help_requests(id) on delete cascade,
    helper_id uuid not null references public.profiles(id) on delete cascade,
    score integer not null check (score between 0 and 100),
    score_components jsonb not null,
    rank integer,
    ranked_above_previous_by text,
    updated_at timestamptz not null default now(),
    primary key (request_id, helper_id)
);

create index if not exists profiles_role_idx on public.profiles(role);
create index if not exists requests_seeker_idx on public.help_requests(seeker_id);
create index if not exists connections_helper_idx on public.connections(helper_id);
create index if not exists connections_request_idx on public.connections(request_id);
create index if not exists match_results_helper_idx on public.match_results(helper_id);
create index if not exists helper_ratings_helper_idx on public.helper_ratings(helper_id);

