create table if not exists public.help_requests (
    id bigint generated by default as identity primary key,
    seeker_id uuid not null references public.profiles(id) on delete cascade,
    description text not null check (char_length(description) between 1 and 1000),
    category text not null default 'Community Support',
    skill text not null default '',
    location text not null default '',
    availability text not null default 'Flexible',
    language text not null default 'it',
    skill_tags text[] not null default '{}',
    availability_slots jsonb not null default '[]'::jsonb,
    place_id text,
    user_lang text check (user_lang is null or user_lang in ('it', 'en')),
    user_lang_confirmed boolean not null default false,
    stated_lang text,
    translation_ok boolean not null default false,
    explicit_constraints jsonb not null default '{}'::jsonb,
    number_constraints jsonb not null default '[]'::jsonb,
    emergency boolean not null default false,
    medical boolean not null default false,
    urgency text not null default 'normal' check (urgency in ('normal', 'soon', 'urgent')),
    is_demo boolean not null default false,
    status text not null default 'open' check (status in ('open', 'closed')),
    created_at timestamptz not null default now()
);

