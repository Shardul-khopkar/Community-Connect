create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    name text not null check (char_length(name) between 1 and 80),
    email text not null unique,
    phone text,
    location text,
    role text not null check (role in ('seeker', 'helper', 'volunteer', 'ngo', 'admin')),
    skills text not null default '',
    languages text not null default '',
    availability text not null default '',
    skill_tags text[] not null default '{}',
    categories text[] not null default '{}',
    spoken_languages text[] not null default '{}',
    numeric_offers jsonb not null default '[]'::jsonb,
    availability_slots jsonb not null default '[]'::jsonb,
    place_id text,
    max_travel_km numeric check (max_travel_km is null or max_travel_km > 0),
    active boolean not null default false,
    response_rate numeric check (response_rate is null or response_rate between 0 and 1),
    average_response_seconds numeric check (average_response_seconds is null or average_response_seconds >= 0),
    experience text not null default '',
    bio text not null default '',
    self_reported boolean not null default true,
    is_demo boolean not null default false,
    needs_review boolean not null default false,
    consent_at timestamptz not null default now(),
    created_at timestamptz not null default now()
);

