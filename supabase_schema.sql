-- CommunityConnect schema for Supabase/Postgres.
-- Run this in Supabase SQL Editor, then point the Flask app at Supabase.

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    name text not null,
    email text not null unique,
    password_hash text,
    phone text,
    location text,
    role text not null check (role in ('seeker', 'helper', 'volunteer', 'ngo', 'admin')),
    skills text,
    availability text,
    experience text,
    bio text,
    verified boolean not null default true,
    skill_verified boolean not null default false,
    needs_review boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.help_requests (
    id bigint generated by default as identity primary key,
    seeker_id bigint not null references public.users(id) on delete cascade,
    description text not null,
    category text,
    ai_category text,
    ai_confidence_score numeric(4,3),
    skill text,
    location text,
    availability text,
    status text not null default 'open'
        check (status in ('open', 'matched', 'closed', 'cancelled', 'expired')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.connections (
    id bigint generated by default as identity primary key,
    request_id bigint not null references public.help_requests(id) on delete cascade,
    helper_id bigint not null references public.users(id) on delete cascade,
    score integer not null check (score between 0 and 100),
    match_breakdown jsonb not null default '{}'::jsonb,
    status text not null default 'pending'
        check (status in ('pending', 'accepted', 'rejected', 'withdrawn', 'expired', 'closed')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (request_id, helper_id)
);

-- Keep an already-created database compatible when this migration is rerun.
alter table public.help_requests add column if not exists ai_category text;
alter table public.help_requests add column if not exists ai_confidence_score numeric(4,3);
alter table public.help_requests add column if not exists updated_at timestamptz not null default now();
alter table public.connections add column if not exists match_breakdown jsonb not null default '{}'::jsonb;
alter table public.connections add column if not exists updated_at timestamptz not null default now();
alter table public.users add column if not exists password_hash text;

alter table public.connections drop constraint if exists connections_status_check;
alter table public.connections add constraint connections_status_check
    check (status in ('pending', 'accepted', 'rejected', 'withdrawn', 'expired', 'closed'));
alter table public.help_requests drop constraint if exists help_requests_status_check;
alter table public.help_requests add constraint help_requests_status_check
    check (status in ('open', 'matched', 'closed', 'cancelled', 'expired'));

create table if not exists public.activity_logs (
    id bigint generated by default as identity primary key,
    request_id bigint references public.help_requests(id) on delete cascade,
    connection_id bigint references public.connections(id) on delete cascade,
    actor_id bigint references public.users(id) on delete set null,
    actor_type text not null check (actor_type in ('seeker', 'helper', 'admin', 'system')),
    action text not null,
    from_status text,
    to_status text,
    reason text,
    message text not null,
    created_at timestamptz not null default now()
);

create index if not exists help_requests_seeker_id_idx
    on public.help_requests(seeker_id);
create index if not exists connections_request_id_idx
    on public.connections(request_id);
create index if not exists connections_helper_id_idx
    on public.connections(helper_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists connections_set_updated_at on public.connections;
create trigger connections_set_updated_at
before update on public.connections
for each row execute function public.set_updated_at();

drop trigger if exists help_requests_set_updated_at on public.help_requests;
create trigger help_requests_set_updated_at
before update on public.help_requests
for each row execute function public.set_updated_at();

-- The Flask backend should connect with Supabase's service-role key.
-- RLS prevents accidental public access when the tables are exposed through PostgREST.
alter table public.users enable row level security;
alter table public.help_requests enable row level security;
alter table public.connections enable row level security;
alter table public.activity_logs enable row level security;
